#!/usr/bin/env python3
"""Generate a mnemo workflow definition for every active OpenSpec change.

Reads openspec/changes/<slug>/tasks.md, groups the remaining unchecked
`- [ ]` tasks under their `## N.` headings, and writes
openspec/changes/<slug>/workflow.yaml — one delegate step per group.

Skips: the archive/ directory, the already-registered `split-graphos-studio`
change (it has a running run), and any change with no remaining unchecked
tasks (already implemented or a different format).
"""

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHANGES = os.path.join(ROOT, "openspec", "changes")

HEADING = re.compile(r"^##\s+(.+)$")
TASK = re.compile(r"^\s*-\s*\[ \]\s*(.*)$")


def parse_groups(path):
    groups = []
    cur_head = None
    cur_bullets = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            m = HEADING.match(line)
            if m:
                if cur_head is not None and cur_bullets:
                    groups.append((cur_head, cur_bullets))
                cur_head = m.group(1).strip()
                cur_bullets = []
                continue
            b = TASK.match(line)
            if b and cur_head is not None:
                cur_bullets.append(b.group(1).strip())
    if cur_head is not None and cur_bullets:
        groups.append((cur_head, cur_bullets))
    return groups


def emit(slug, groups):
    lines = [
        "# Workflow for the OpenSpec change `%s` (generated by" % slug,
        "# scripts/gen-graphos-workflows.py). One delegate step per task group.",
        "",
        "workflow: %s" % slug,
        "params: []",
        "",
        "steps:",
    ]
    prev = None
    for i, (heading, bullets) in enumerate(groups, start=1):
        sid = "s%d" % i
        lines.append("  - id: %s" % sid)
        lines.append("    executor: delegate")
        lines.append("    target: opencode-deepseek")
        if prev is not None:
            lines.append("    depends_on: [%s]" % prev)
        lines.append("    instruction: |-")
        lines.append(
            "      %s — OpenSpec change `%s` (openspec/changes/%s/)."
            % (heading, slug, slug)
        )
        lines.append(
            "      Read proposal.md, design.md, specs/ and tasks.md first; make the"
        )
        lines.append(
            "      code changes in this repo, run the build and tests, then commit."
        )
        lines.append("      Tasks:")
        for b in bullets:
            lines.append("      - %s" % b)
        lines.append("")
        prev = sid
    return "\n".join(lines).rstrip() + "\n"


def main():
    created = []
    skipped = []
    for name in sorted(os.listdir(CHANGES)):
        if name == "archive":
            continue
        slug = name
        d = os.path.join(CHANGES, name)
        if not os.path.isdir(d):
            continue
        tasks = os.path.join(d, "tasks.md")
        if not os.path.isfile(tasks):
            skipped.append((slug, "no tasks.md"))
            continue
        if slug == "split-graphos-studio":
            skipped.append((slug, "already registered + running"))
            continue
        groups = parse_groups(tasks)
        if not groups:
            skipped.append((slug, "no unchecked tasks"))
            continue
        out = os.path.join(d, "workflow.yaml")
        with open(out, "w", encoding="utf-8") as f:
            f.write(emit(slug, groups))
        created.append((slug, len(groups)))

    print("created %d workflow(s):" % len(created))
    for slug, n in created:
        print("  %-40s %d step(s)" % (slug, n))
    print("skipped %d:" % len(skipped))
    for slug, why in skipped:
        print("  %-40s %s" % (slug, why))


if __name__ == "__main__":
    main()
