#!/usr/bin/env bash
# Codegen pre-step for the graphos binary contract test (AVI-1071).
#
# Elm tests cannot read files at runtime, so real graphos output (the
# `graphos-fixture` CI artifact: graph.json files produced by the graphos
# binary) is embedded as Elm string constants in ContractFixtures.elm, which
# ContractTest.elm decodes through the studio graph decoders. The committed
# ContractFixtures.elm is an empty placeholder; CI regenerates it from the
# downloaded artifact before running elm-test.
#
# Usage: generate-contract-fixtures.sh <fixtures-dir> [<output.elm>]
#   <fixtures-dir>  directory containing <name>.graph.json files
#                   (flat per-input names, e.g. generated.rs.graph.json)
#   <output.elm>    output module path
#                   (default: ContractFixtures.elm next to this script)
#
# Fails when no *.graph.json files are found — an empty generated module
# would make the contract suite silently pass with nothing checked.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SRC_DIR="${1:?usage: generate-contract-fixtures.sh <fixtures-dir> [<output.elm>]}"
OUT_FILE="${2:-"$SCRIPT_DIR/ContractFixtures.elm"}"

python3 - "$SRC_DIR" "$OUT_FILE" <<'PY'
import json
import os
import sys

src_dir, out_file = sys.argv[1], sys.argv[2]
files = sorted(
    f
    for f in os.listdir(src_dir)
    if f.endswith(".graph.json") and os.path.isfile(os.path.join(src_dir, f))
)
if not files:
    sys.stderr.write(f"no *.graph.json files found in {src_dir}\n")
    sys.exit(1)

entries = []
for f in files:
    with open(os.path.join(src_dir, f), encoding="utf-8") as fh:
        raw = fh.read()
    json.loads(raw)  # must parse: these are real payloads, not opaque blobs
    if '"""' in raw:
        sys.stderr.write(f"{f}: contains \"\"\" — cannot be embedded in an Elm string\n")
        sys.exit(1)
    # Elm 0.19.2 multi-line (\"\"\") strings process backslash escapes, so a
    # raw backslash in the payload must be doubled for the runtime value to
    # carry the exact JSON bytes (labels contain \n, \" etc.).
    embedded = raw.rstrip("\n").replace("\\", "\\\\")
    entries.append((f[: -len(".graph.json")], embedded))

lines = [
    "module ContractFixtures exposing (fixtures)",
    "",
    "{-| GENERATED by studio/tests/generate-contract-fixtures.sh — do not edit.",
    "Real graph.json output produced by the graphos binary (the CI artifact",
    "`graphos-fixture`), embedded as Elm string constants because elm-test",
    "cannot read files at test runtime. The repo carries a placeholder with an",
    "empty list; CI regenerates this module from the downloaded artifact before",
    "running the contract suite (AVI-1071).",
    "-}",
    "",
    "fixtures : List ( String, String )",
    "fixtures =",
    "    [",
]
for i, (name, raw) in enumerate(entries):
    comma = "," if i < len(entries) - 1 else ""
    lines.append(f'      ( "{name}"')
    lines.append('      , """')
    lines.append(raw)
    lines.append(f'""" ){comma}')
lines.append("    ]")

with open(out_file, "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines) + "\n")
print(f"wrote {out_file}: {len(entries)} fixture(s) — " + ", ".join(n for n, _ in entries))
PY